#!/usr/bin/env python3
"""Generates builds/ios/Helm_iOS.xcodeproj.

Helm ships with JUCE 5.3.2 but without the Projucer sources, so the iOS
project (AUv3 app extension + its container app) is generated here instead
of being hand-maintained.  Re-run this script after adding or removing source
files:

    python builds/ios/generate_project.py
"""

import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))

PROJECT_NAME = "Helm"
APP_BUNDLE_ID = "org.tytel.helm"
AUV3_BUNDLE_ID = APP_BUNDLE_ID + ".auv3"
DEPLOYMENT_TARGET = "17.0"

# Helm sources compiled into the shared static library that both the app and
# the AUv3 extension link against.
SHARED_SOURCE_DIRS = [
    "src/common",
    "src/editor_components",
    "src/editor_sections",
    "src/look_and_feel",
    "src/plugin",
    "src/synthesis",
    "mopo/src",
]

# JUCE module implementation files (JuceLibraryCode wrappers generated by the
# Projucer for this project).
SHARED_JUCE_FILES = [
    "BinaryData.cpp",
    "include_juce_audio_basics.mm",
    "include_juce_audio_devices.mm",
    "include_juce_audio_formats.mm",
    "include_juce_audio_plugin_client_utils.cpp",
    "include_juce_audio_processors.mm",
    "include_juce_audio_utils.mm",
    "include_juce_core.mm",
    "include_juce_data_structures.mm",
    "include_juce_events.mm",
    "include_juce_graphics.mm",
    "include_juce_gui_basics.mm",
    "include_juce_gui_extra.mm",
    "include_juce_opengl.mm",
]

AUV3_SOURCE = "JuceLibraryCode/include_juce_audio_plugin_client_AUv3.mm"
APP_SOURCE = "JuceLibraryCode/include_juce_audio_plugin_client_Standalone.cpp"

HEADER_SEARCH_PATHS = [
    '"$(inherited)"',
    '"../../JuceLibraryCode"',
    '"../../JUCE/modules"',
    '"../../concurrentqueue"',
    '"../../mopo/src"',
    '"../../src"',
    '"../../src/common"',
    '"../../src/editor_components"',
    '"../../src/editor_sections"',
    '"../../src/look_and_feel"',
    '"../../src/synthesis"',
    '"../../JUCE/modules/juce_audio_plugin_client"',
]

# Frameworks are all SDK frameworks, so plain -framework flags keep the pbxproj
# free of SDK-relative file references.
FRAMEWORKS = [
    "Accelerate",
    "AudioToolbox",
    "AudioUnit",
    "AVFoundation",
    "CoreAudio",
    "CoreAudioKit",
    "CoreGraphics",
    "CoreMIDI",
    "CoreServices",
    "CoreText",
    "CoreVideo",
    "Foundation",
    "ImageIO",
    "MobileCoreServices",
    "OpenGLES",
    "QuartzCore",
    "Security",
    "UIKit",
]

COMMON_DEFINES = [
    "JUCE_APP_VERSION=0.9.0",
    "JUCE_APP_VERSION_HEX=0x900",
    "JUCE_DISPLAY_SPLASH_SCREEN=0",
    "JUCE_REPORT_APP_USAGE=0",
    "JUCE_WEB_BROWSER=0",
    "JUCE_USE_CURL=0",
]

# JUCE 5.3.2 predates the diagnostics modern clang promotes to errors.
LEGACY_CLANG_FLAGS = [
    "-Wno-error=implicit-function-declaration",
    "-Wno-error=incompatible-function-pointer-types",
    "-Wno-error=int-conversion",
    "-Wno-error=deprecated-declarations",
    "-Wno-error=return-type",
]

# old-style plist values may only be bare if they avoid characters such as '='.
LEGACY_CLANG_FLAGS = ['"%s"' % flag for flag in LEGACY_CLANG_FLAGS]


def ident(key):
    return hashlib.md5(key.encode("utf-8")).hexdigest().upper()[:24]


def q(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def file_type(path):
    if path.endswith(".mm"):
        return "sourcecode.cpp.objcpp"
    if path.endswith(".cpp"):
        return "sourcecode.cpp.cpp"
    if path.endswith(".c"):
        return "sourcecode.c.c"
    if path.endswith(".h") or path.endswith(".hpp"):
        return "sourcecode.c.h"
    if path.endswith(".plist"):
        return "text.plist.xml"
    return "text"


def collect_sources():
    sources = []
    for directory in SHARED_SOURCE_DIRS:
        path = os.path.join(REPO, directory)
        for name in sorted(os.listdir(path)):
            if name.endswith(".cpp"):
                sources.append((directory + "/" + name).replace("\\", "/"))
    sources.extend("JuceLibraryCode/" + name for name in SHARED_JUCE_FILES)
    return sorted(sources)


class Project:
    def __init__(self):
        self.objects = {}
        self.order = []

    def add(self, key, body, comment=""):
        oid = ident(key)
        if oid in self.objects:
            raise RuntimeError("duplicate object id for " + key)
        self.objects[oid] = (body, comment)
        self.order.append(oid)
        return oid

    def ref(self, key):
        return ident(key)

    def render(self):
        sections = {}
        for oid in self.order:
            body, comment = self.objects[oid]
            isa = body.split("isa = ")[1].split(";")[0]
            entry = "\t\t%s /* %s */ = %s;\n" % (oid, comment, body)
            sections.setdefault(isa, []).append(entry)

        out = ["// !$*UTF8*$!\n{\n", "\tarchiveVersion = 1;\n", "\tclasses = {\n\t};\n",
               "\tobjectVersion = 56;\n", "\tobjects = {\n"]
        for name in sorted(sections):
            out.append("\n/* Begin %s section */\n" % name)
            out.extend(sections[name])
            out.append("/* End %s section */\n" % name)
        out.append("\t};\n")
        out.append("\trootObject = %s /* Project object */;\n}\n" % ident("project"))
        return "".join(out)


def settings_block(settings, indent):
    pad = "\t" * indent
    lines = []
    for key, value in settings.items():
        if isinstance(value, list):
            lines.append("%s%s = (\n" % (pad, key))
            for item in value:
                lines.append("%s\t%s,\n" % (pad, item))
            lines.append("%s);\n" % pad)
        else:
            lines.append("%s%s = %s;\n" % (pad, key, value))
    return "".join(lines)


def plugin_defines(kind):
    return [
        "JucePlugin_Build_VST=0",
        "JucePlugin_Build_VST3=0",
        "JucePlugin_Build_AU=0",
        "JucePlugin_Build_AUv3=1" if kind == "au" else "JucePlugin_Build_AUv3=0",
        "JucePlugin_Build_RTAS=0",
        "JucePlugin_Build_AAX=0",
        "JucePlugin_Build_Standalone=1" if kind == "app" else "JucePlugin_Build_Standalone=0",
    ]


def target_settings(config, kind):
    debug = config == "Debug"
    defines = list(COMMON_DEFINES) + plugin_defines(kind)
    debug_defines = ['"_DEBUG=1"', '"DEBUG=1"'] if debug else ['"_NDEBUG=1"', '"NDEBUG=1"']
    defines = debug_defines + [q(d) for d in defines]

    ldflags = ['"$(inherited)"', '"-ObjC"']
    for framework in FRAMEWORKS:
        ldflags.append('"-framework"')
        ldflags.append(q(framework))

    settings = {
        "CLANG_CXX_LANGUAGE_STANDARD": '"c++14"',
        "CLANG_CXX_LIBRARY": '"libc++"',
        "CLANG_ENABLE_MODULES": "YES",
        "CLANG_ENABLE_OBJC_ARC": "YES",
        "CODE_SIGN_STYLE": "Automatic",
        "GCC_NO_COMMON_BLOCKS": "YES",
        "GCC_PREPROCESSOR_DEFINITIONS": defines,
        "HEADER_SEARCH_PATHS": HEADER_SEARCH_PATHS,
        "IPHONEOS_DEPLOYMENT_TARGET": DEPLOYMENT_TARGET,
        "OTHER_CFLAGS": LEGACY_CLANG_FLAGS,
        "OTHER_LDFLAGS": ldflags,
        "SDKROOT": "iphoneos",
        "SUPPORTED_PLATFORMS": '"iphoneos iphonesimulator"',
        "TARGETED_DEVICE_FAMILY": '"1,2"',
        "USE_HEADERMAP": "NO",
        "ENABLE_USER_SCRIPT_SANDBOXING": "NO",
        "COPY_PHASE_STRIP": "NO",
        "DEBUG_INFORMATION_FORMAT": "dwarf" if debug else '"dwarf-with-dsym"',
    }

    if debug:
        settings.update({
            "ENABLE_TESTABILITY": "YES",
            "GCC_DYNAMIC_NO_PIC": "NO",
            "GCC_OPTIMIZATION_LEVEL": "0",
            "ONLY_ACTIVE_ARCH": "YES",
        })
    else:
        settings.update({
            "ENABLE_NS_ASSERTIONS": "NO",
            "GCC_OPTIMIZATION_LEVEL": "s",
            "VALIDATE_PRODUCT": "YES",
        })

    settings["PRODUCT_NAME"] = q(PROJECT_NAME)
    # The app extension may only link extension-safe code, and Xcode enforces
    # this for every target in the dependency graph.
    settings["APPLICATION_EXTENSION_API_ONLY"] = "YES"

    if kind == "lib":
        settings["EXECUTABLE_PREFIX"] = "lib"
        settings["SKIP_INSTALL"] = "YES"
    elif kind == "au":
        settings["PRODUCT_BUNDLE_IDENTIFIER"] = q(AUV3_BUNDLE_ID)
        settings["INFOPLIST_FILE"] = q("Info-AUv3.plist")
        settings["SKIP_INSTALL"] = "YES"
        settings["LD_RUNPATH_SEARCH_PATHS"] = [
            '"$(inherited)"',
            '"@executable_path/Frameworks"',
            '"@executable_path/../../Frameworks"',
        ]
    else:
        settings["PRODUCT_BUNDLE_IDENTIFIER"] = q(APP_BUNDLE_ID)
        settings["INFOPLIST_FILE"] = q("Info-App.plist")
        settings["LD_RUNPATH_SEARCH_PATHS"] = [
            '"$(inherited)"',
            '"@executable_path/Frameworks"',
        ]

    return settings


def project_settings(config):
    debug = config == "Debug"
    settings = {
        "ALWAYS_SEARCH_USER_PATHS": "NO",
        "CLANG_CXX_LANGUAGE_STANDARD": '"c++14"',
        "CLANG_CXX_LIBRARY": '"libc++"',
        "CLANG_ENABLE_MODULES": "YES",
        "CLANG_ENABLE_OBJC_ARC": "YES",
        "ENABLE_STRICT_OBJC_MSGSEND": "YES",
        "GCC_C_LANGUAGE_STANDARD": "gnu11",
        "GCC_NO_COMMON_BLOCKS": "YES",
        "IPHONEOS_DEPLOYMENT_TARGET": DEPLOYMENT_TARGET,
        "SDKROOT": "iphoneos",
        "GCC_OPTIMIZATION_LEVEL": "0" if debug else "s",
        "DEBUG_INFORMATION_FORMAT": "dwarf" if debug else '"dwarf-with-dsym"',
    }
    if debug:
        settings["ONLY_ACTIVE_ARCH"] = "YES"
    else:
        settings["ENABLE_NS_ASSERTIONS"] = "NO"
    return settings


def main():
    project = Project()

    shared_sources = collect_sources()
    all_source_paths = sorted(set(shared_sources + [AUV3_SOURCE, APP_SOURCE]))
    names = {"lib": "Helm - Shared Code", "au": "Helm - AUv3", "app": "Helm - AUv3 App"}
    product_types = {"lib": "library.static", "au": "app-extension", "app": "application"}
    product_names = {"lib": "lib%s.a" % PROJECT_NAME,
                     "au": "%s.appex" % PROJECT_NAME,
                     "app": "%s.app" % PROJECT_NAME}

    # ---- file references ------------------------------------------------
    for path in all_source_paths:
        name = path.split("/")[-1]
        project.add("fr:" + path,
                    '{isa = PBXFileReference; lastKnownFileType = %s; name = %s; '
                    'path = %s; sourceTree = "SOURCE_ROOT"; }'
                    % (file_type(path), q(name), q("../../" + path)),
                    comment=name)

    for plist_name in ("Info-AUv3.plist", "Info-App.plist"):
        project.add("fr:" + plist_name,
                    '{isa = PBXFileReference; lastKnownFileType = text.plist.xml; '
                    'name = %s; path = %s; sourceTree = "SOURCE_ROOT"; }'
                    % (q(plist_name), q(plist_name)),
                    comment=plist_name)

    project.add("fr:patches",
                '{isa = PBXFileReference; lastKnownFileType = folder; name = patches; '
                'path = "../../patches"; sourceTree = "SOURCE_ROOT"; }',
                comment="patches")

    products = {}
    for kind in ("lib", "au", "app"):
        explicit = {"lib": "archive.ar", "au": '"wrapper.app-extension"',
                    "app": '"wrapper.application"'}[kind]
        products[kind] = project.add(
            "fr:product:" + kind,
            '{isa = PBXFileReference; explicitFileType = %s; includeInIndex = 0; '
            'path = %s; sourceTree = BUILT_PRODUCTS_DIR; }'
            % (explicit, product_names[kind]),
            comment=product_names[kind])

    # ---- groups ---------------------------------------------------------
    source_group_children = "".join(
        "\t\t\t%s /* %s */,\n" % (project.ref("fr:" + p), p.split("/")[-1])
        for p in all_source_paths)
    config_group_children = "".join(
        "\t\t\t%s /* %s */,\n" % (project.ref("fr:" + n), n)
        for n in ("Info-AUv3.plist", "Info-App.plist"))

    sources_group = project.add(
        "grp:sources",
        '{isa = PBXGroup; children = (\n%s\t\t); name = Sources; sourceTree = "<group>"; }'
        % source_group_children, comment="Sources")
    config_group = project.add(
        "grp:config",
        '{isa = PBXGroup; children = (\n%s\t\t); name = Config; sourceTree = "<group>"; }'
        % config_group_children, comment="Config")
    resources_group = project.add(
        "grp:resources",
        '{isa = PBXGroup; children = (\n\t\t\t%s /* patches */,\n\t\t); name = Resources; '
        'sourceTree = "<group>"; }' % project.ref("fr:patches"), comment="Resources")
    products_group = project.add(
        "grp:products",
        '{isa = PBXGroup; children = (\n%s\t\t); name = Products; sourceTree = "<group>"; }'
        % "".join("\t\t\t%s /* %s */,\n" % (products[k], product_names[k])
                  for k in ("lib", "au", "app")), comment="Products")
    main_group = project.add(
        "grp:main",
        '{isa = PBXGroup; children = (\n\t\t\t%s /* Sources */,\n\t\t\t%s /* Config */,\n'
        '\t\t\t%s /* Resources */,\n\t\t\t%s /* Products */,\n\t\t); sourceTree = "<group>"; }'
        % (sources_group, config_group, resources_group, products_group), comment="Main")

    # ---- build files ----------------------------------------------------
    def build_file(key, file_ref, comment):
        return project.add("bf:%s" % key,
                           '{isa = PBXBuildFile; fileRef = %s /* %s */; }'
                           % (file_ref, comment),
                           comment=comment + " in Sources")

    shared_build_files = [build_file("src:" + p, project.ref("fr:" + p), p.split("/")[-1])
                          for p in shared_sources]
    au_build_files = [build_file("src:" + AUV3_SOURCE, project.ref("fr:" + AUV3_SOURCE),
                                 AUV3_SOURCE.split("/")[-1])]
    app_build_files = [build_file("src:" + APP_SOURCE, project.ref("fr:" + APP_SOURCE),
                                  APP_SOURCE.split("/")[-1])]

    link_build_files = {}
    for kind in ("au", "app"):
        link_build_files[kind] = project.add(
            "bf:link:%s" % kind,
            '{isa = PBXBuildFile; fileRef = %s /* lib%s.a */; }'
            % (products["lib"], PROJECT_NAME),
            comment="lib%s.a in Frameworks" % PROJECT_NAME)

    resource_build_files = {}
    for kind in ("au", "app"):
        resource_build_files[kind] = project.add(
            "bf:res:%s" % kind,
            '{isa = PBXBuildFile; fileRef = %s /* patches */; }' % project.ref("fr:patches"),
            comment="patches in Resources")

    embed_build_file = project.add(
        "bf:embed:au",
        '{isa = PBXBuildFile; fileRef = %s /* %s.appex */; settings = {ATTRIBUTES = '
        '(RemoveHeadersOnCopy, ); }; }' % (products["au"], PROJECT_NAME),
        comment="%s.appex in Embed App Extensions" % PROJECT_NAME)

    # ---- build phases ---------------------------------------------------
    def sources_phase(key, files):
        return project.add(
            "phase:sources:" + key,
            '{isa = PBXSourcesBuildPhase; buildActionMask = 2147483647; files = (\n%s\t\t); '
            'runOnlyForDeploymentPostprocessing = 0; }'
            % "".join("\t\t\t%s,\n" % f for f in files), comment="Sources")

    def frameworks_phase(key, files):
        return project.add(
            "phase:frameworks:" + key,
            '{isa = PBXFrameworksBuildPhase; buildActionMask = 2147483647; files = (\n%s\t\t); '
            'runOnlyForDeploymentPostprocessing = 0; }'
            % ("".join("\t\t\t%s,\n" % f for f in files)), comment="Frameworks")

    def resources_phase(key, files):
        return project.add(
            "phase:resources:" + key,
            '{isa = PBXResourcesBuildPhase; buildActionMask = 2147483647; files = (\n%s\t\t); '
            'runOnlyForDeploymentPostprocessing = 0; }'
            % ("".join("\t\t\t%s,\n" % f for f in files)), comment="Resources")

    phases = {
        "lib": [sources_phase("lib", shared_build_files), frameworks_phase("lib", [])],
        "au": [sources_phase("au", au_build_files),
               frameworks_phase("au", [link_build_files["au"]]),
               resources_phase("au", [resource_build_files["au"]])],
        "app": [sources_phase("app", app_build_files),
                frameworks_phase("app", [link_build_files["app"]]),
                resources_phase("app", [resource_build_files["app"]]),
                project.add(
                    "phase:embed:au",
                    '{isa = PBXCopyFilesBuildPhase; buildActionMask = 2147483647; '
                    'dstPath = ""; dstSubfolderSpec = 13; files = (\n\t\t\t%s,\n\t\t); '
                    'name = "Embed App Extensions"; runOnlyForDeploymentPostprocessing = 0; }'
                    % embed_build_file,
                    comment="Embed App Extensions")],
    }

    # ---- targets --------------------------------------------------------
    target_ids = {}

    def dependency(key, target, product_kind):
        proxy = project.add(
            "proxy:" + key,
            '{isa = PBXContainerItemProxy; containerPortal = %s /* Project object */; '
            'proxyType = 1; remoteGlobalIDString = %s; remoteInfo = %s; }'
            % (project.ref("project"), target, q(names[product_kind])),
            comment="PBXContainerItemProxy")
        return project.add(
            "dep:" + key,
            '{isa = PBXTargetDependency; target = %s /* %s */; targetProxy = %s '
            '/* PBXContainerItemProxy */; }' % (target, names[product_kind], proxy),
            comment="PBXTargetDependency")

    for kind in ("lib", "au", "app"):
        build_config_list = project.add(
            "cl:" + kind,
            '{isa = XCConfigurationList; buildConfigurations = (\n%s\t\t); '
            'defaultConfigurationIsVisible = 0; defaultConfigurationName = Release; }'
            % "".join("\t\t\t%s /* %s */,\n"
                      % (project.ref("bc:%s:%s" % (kind, config)), config)
                      for config in ("Debug", "Release")),
            comment='Build configuration list for PBXNativeTarget "%s"' % names[kind])

        dependencies = []
        if kind == "au":
            dependencies.append(dependency("au:lib", target_ids["lib"], "lib"))
        elif kind == "app":
            dependencies.append(dependency("app:lib", target_ids["lib"], "lib"))
            dependencies.append(dependency("app:au", target_ids["au"], "au"))

        target_ids[kind] = project.add(
            "target:" + kind,
            '{isa = PBXNativeTarget; buildConfigurationList = %s /* Build configuration '
            'list for PBXNativeTarget "%s" */; buildPhases = (\n%s\t\t); buildRules = (\n\t\t); '
            'dependencies = (\n%s\t\t); name = %s; productName = %s; productReference = %s '
            '/* %s */; productType = "com.apple.product-type.%s"; }'
            % (build_config_list, names[kind],
               "".join("\t\t\t%s,\n" % phase for phase in phases[kind]),
               "".join("\t\t\t%s,\n" % dep for dep in dependencies),
               q(names[kind]), PROJECT_NAME, products[kind], product_names[kind],
               product_types[kind]),
            comment=names[kind])

    # ---- configurations -------------------------------------------------
    for kind in ("project", "lib", "au", "app"):
        for config in ("Debug", "Release"):
            settings = project_settings(config) if kind == "project" \
                else target_settings(config, kind)
            project.add(
                "bc:%s:%s" % (kind, config),
                '{isa = XCBuildConfiguration; buildSettings = {\n%s\t\t\t}; name = %s; }'
                % (settings_block(settings, 4), config),
                comment=config)

    project_config_list = project.add(
        "cl:project",
        '{isa = XCConfigurationList; buildConfigurations = (\n\t\t\t%s /* Debug */,\n'
        '\t\t\t%s /* Release */,\n\t\t); defaultConfigurationIsVisible = 0; '
        'defaultConfigurationName = Release; }'
        % (project.ref("bc:project:Debug"), project.ref("bc:project:Release")),
        comment='Build configuration list for PBXProject "%s"' % PROJECT_NAME)

    # ---- project --------------------------------------------------------
    project.add(
        "project",
        '{isa = PBXProject; attributes = { LastUpgradeCheck = 1500; '
        'ORGANIZATIONNAME = "Matt Tytel"; }; buildConfigurationList = %s '
        '/* Build configuration list for PBXProject "%s" */; compatibilityVersion = '
        '"Xcode 14.0"; developmentRegion = en; hasScannedForEncodings = 0; knownRegions = '
        '(\n\t\t\ten,\n\t\t\tBase,\n\t\t); mainGroup = %s; productRefGroup = %s /* Products */; '
        'projectDirPath = ""; projectRoot = ""; targets = (\n%s\t\t); }'
        % (project_config_list, PROJECT_NAME, main_group, products_group,
           "".join("\t\t\t%s /* %s */,\n" % (target_ids[k], names[k])
                   for k in ("lib", "au", "app"))),
        comment="Project object")

    out_path = os.path.join(HERE, "Helm_iOS.xcodeproj")
    if not os.path.isdir(out_path):
        os.makedirs(out_path)
    target_file = os.path.join(out_path, "project.pbxproj")
    with open(target_file, "w", newline="\n") as handle:
        handle.write(project.render())
    print("wrote %s (%d objects)" % (target_file, len(project.order)))


if __name__ == "__main__":
    main()

